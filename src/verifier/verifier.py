"""Verifier role. It never receives the reference solution or reference answer:
its functions only take the question text and model outputs.

Two levels:
  basic_check(solution)   cheap, deterministic: extractable answer, explicit
                          arithmetic consistency, truncation, answer form.
  pot_check(program_out)  "VERIFY_MORE": an independent program-of-thought
                          computation (generated by the solver model, run by a
                          safe interpreter) whose result is compared with the
                          current candidate answer. Deterministic, so it is
                          offered at most once per episode (action mask).

Interpretation limits (also in the docs):
  * "no error found" != "proven correct";
  * consistent arithmetic does not prove the problem was modelled correctly;
  * PoT agreement is correlated evidence (same model), not ground truth.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from fractions import Fraction
from functools import lru_cache

from src.data.answers import canonical_str, parse_answer_number
from src.solver.extract import extract_final_answer
from src.solver.prompts import extract_code_block

from .arithmetic import check_arithmetic
from .safe_eval import safe_run_program


@dataclass(frozen=True)
class BasicCheck:
    has_answer: bool
    answer: str | None              # canonical form, e.g. "18", "7/2"
    extraction_method: str
    truncated: bool
    arith_checked: int
    arith_errors: int
    arith_status: str               # none_found | all_consistent | error_found
    answer_is_integer: bool | None
    answer_negative: bool | None

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class PotCheck:
    pot_answer: str | None
    status: str                     # ok | no_code | <interpreter error tag>

    def to_dict(self) -> dict:
        return asdict(self)


def basic_check(solution_text: str, finished: bool) -> BasicCheck:
    """Deterministic; memoized because cached replay re-checks the same texts many times."""
    return _basic_check_cached(solution_text, finished)


def pot_check(program_output_text: str) -> PotCheck:
    return _pot_check_cached(program_output_text)


@lru_cache(maxsize=200_000)
def _basic_check_cached(solution_text: str, finished: bool) -> BasicCheck:
    ans, method = extract_final_answer(solution_text)
    rep = check_arithmetic(solution_text)
    val = parse_answer_number(ans) if ans is not None else None
    return BasicCheck(
        has_answer=ans is not None,
        answer=ans,
        extraction_method=method,
        truncated=not finished,
        arith_checked=rep.checked,
        arith_errors=rep.errors,
        arith_status=rep.status,
        answer_is_integer=(val.denominator == 1) if val is not None else None,
        answer_negative=(val < 0) if val is not None else None,
    )


@lru_cache(maxsize=50_000)
def _pot_check_cached(program_output_text: str) -> PotCheck:
    code = extract_code_block(program_output_text)
    if code is None:
        return PotCheck(None, "no_code")
    value, status = safe_run_program(code)
    if value is None:
        return PotCheck(None, status)
    return PotCheck(canonical_str(_round_float_noise(value)), "ok")


def _round_float_noise(v: Fraction) -> Fraction:
    """Programs often produce 29.999999999 from float-looking literals. Snap to a
    nearby value with <= 6 decimals when within 1e-9 (no effect on exact values)."""
    snapped = Fraction(round(v * 10**6), 10**6)
    return snapped if abs(snapped - v) < Fraction(1, 10**9) else v


def compare_pot(pot: PotCheck | None, candidate: str | None) -> str:
    """not_run | agree | disagree | failed (PoT produced no number) | no_candidate"""
    if pot is None:
        return "not_run"
    if pot.pot_answer is None:
        return "failed"
    if candidate is None:
        return "no_candidate"
    return "agree" if parse_answer_number(pot.pot_answer) == parse_answer_number(candidate) else "disagree"
